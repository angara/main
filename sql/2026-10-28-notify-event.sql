-- Durable inbound events, replacing Valkey event_queue/event_queue_seq.
create table if not exists notify_event (
  id bigint generated by default as identity primary key,
  type text not null,
  data jsonb not null,
  created_at timestamptz not null default current_timestamp,
  status text not null default 'wait' check (status in ('wait', 'process', 'done', 'failed')),
  available_at timestamptz not null default current_timestamp,
  attempts integer not null default 0,
  locked_until timestamptz,
  processed_at timestamptz,
  last_error text
);

create index if not exists notify_event_pending_idx
  on notify_event (available_at, id) where status in ('wait', 'process');
